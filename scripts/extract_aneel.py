from __future__ import annotations

import csv
import json
import urllib.parse
import zipfile
from pathlib import Path

from src.common import ROOT, ckan_package, download, ensure_dirs, find_resource, http_json, read_config


def main() -> None:
    config = read_config()
    ensure_dirs(config)
    timeout = config["http"]["timeout_seconds"]
    retries = config["http"]["retries"]
    force = config["cache"]["force_download"]
    metadata = []

    siga = config["sources"]["aneel_siga"]
    package = ckan_package(siga["ckan_api"], siga["package_id"], timeout, retries)
    resource = find_resource(package, contains=siga["resource_contains"])
    url = resource["url"]
    print(f"[INFO] ANEEL SIGA resource: {resource.get('name')}")
    metadata.append(download(url, ROOT / "data/raw/aneel_siga.csv", timeout, retries, force))

    mmgd = config["sources"]["aneel_mmgd"]
    package = ckan_package(mmgd["ckan_api"], mmgd["package_id"], timeout, retries)
    resource = find_resource(package, contains=mmgd["resource_contains"])
    url = resource["url"]
    max_records = config["cache"].get("max_mmgd_records", 0)
    print(f"[INFO] ANEEL MMGD resource: {resource.get('name')} ({resource.get('size', 'unknown size')})")
    if max_records and int(max_records) > 0:
        query = urllib.parse.urlencode({"resource_id": resource["id"], "limit": int(max_records)})
        out = ROOT / "data/raw/aneel_mmgd.csv"
        try:
            payload = http_json(f"{mmgd['ckan_api']}/datastore_search?{query}", timeout, retries)
            records = payload.get("result", {}).get("records", [])
            out.parent.mkdir(parents=True, exist_ok=True)
            fieldnames = list(records[0].keys()) if records else []
            with out.open("w", encoding="utf-8", newline="") as handle:
                writer = csv.DictWriter(handle, fieldnames=fieldnames)
                writer.writeheader()
                writer.writerows(records)
        except Exception as exc:  # noqa: BLE001
            print(f"[WARNING] MMGD Datastore extract failed, falling back to official ZIP sample: {exc}")
            zip_path = ROOT / "data/raw/aneel_mmgd_full.zip"
            metadata.append(download(url, zip_path, timeout, retries, force))
            with zipfile.ZipFile(zip_path) as archive:
                csv_name = next(name for name in archive.namelist() if name.lower().endswith(".csv"))
                with archive.open(csv_name) as source, out.open("w", encoding="utf-8", newline="") as target:
                    text = (line.decode("utf-8-sig", errors="replace") for line in source)
                    reader = csv.reader(text, delimiter=";")
                    writer = csv.writer(target)
                    for idx, row in enumerate(reader):
                        if idx > int(max_records):
                            break
                        writer.writerow(row)
        metadata.append({
            "file": str(out.relative_to(ROOT)),
            "url": f"{mmgd['ckan_api']}/datastore_search?resource_id={resource['id']}&limit={max_records}",
            "downloaded_at": "generated by CKAN datastore_search",
            "sha256": "see full resource hash in source portal",
            "bytes": out.stat().st_size,
            "cached": False,
            "note": "Configured limited official Datastore extract. Set cache.max_mmgd_records to 0 for full CSV download.",
        })
    else:
        metadata.append(download(url, ROOT / "data/raw/aneel_mmgd.csv", timeout, retries, force))

    out = ROOT / "data/raw/metadata_aneel.json"
    out.write_text(json.dumps(metadata, ensure_ascii=False, indent=2), encoding="utf-8")
    print("[OK] ANEEL capacity")
    print("[OK] ANEEL MMGD")


if __name__ == "__main__":
    main()
